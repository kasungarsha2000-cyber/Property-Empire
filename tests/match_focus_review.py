"""Exercise quiet receipts, ownership, fullscreen and both sides of counteroffers."""
import os,json
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
out=Path('test-artifacts')
fixtures=json.loads((out/'browser-fixtures.json').read_text(encoding='utf-8'))
base=os.environ.get('EMPIRE_URL','http://127.0.0.1:5173')
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True,args=['--use-angle=swiftshader'])
    try:
        page=browser.new_page(viewport={'width':1440,'height':960});errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.add_init_script("localStorage.setItem('empire-settings',JSON.stringify({speed:'reduced',quality:'low',sound:false}))")
        page.goto(base);page.wait_for_load_state('networkidle')
        def load(key):
            page.evaluate('''async game=>{const db=await new Promise(r=>{const q=indexedDB.open('property-empire-saves',1);q.onupgradeneeded=()=>q.result.createObjectStore('saves');q.onsuccess=()=>r(q.result)});await new Promise(r=>{const t=db.transaction('saves','readwrite');t.objectStore('saves').put({savedAt:Date.now(),game},'current');t.oncomplete=r});db.close()}''',fixtures[key])
            page.get_by_role('button',name='Continue Saved Game',exact=True).click()
        def menu():page.get_by_role('button',name='Main menu',exact=True).click()
        load('purchase')
        page.get_by_role('button',name='Buy for $60',exact=True).click()
        receipt=page.locator('#event-popup')
        expect(receipt).to_have_attribute('role','status')
        expect(receipt).to_contain_text('Property purchased · Copper Lane')
        assert receipt.bounding_box()['height']<=72
        expect(receipt.locator('.event-art')).to_have_count(0)
        page.screenshot(path=str(out/'quiet-receipt.png'))
        expect(receipt).to_be_hidden(timeout=5000)
        expect(page.locator('.ownership-legend')).to_contain_text('YOURS')
        expect(page.locator('.owned-check')).to_have_text('Yours')
        page.get_by_role('button',name='Inspect your Copper Lane',exact=True).click()
        expect(page.locator('#dialog .deed-yours')).to_have_text('✓ Your property')
        page.get_by_role('button',name='Close dialog',exact=True).click()
        page.get_by_role('button',name='Fullscreen',exact=True).click()
        expect(page.locator('body')).to_have_class('match-fullscreen')
        assert page.evaluate('!!document.fullscreenElement')
        expect(page.locator('.topbar')).to_be_hidden()
        stage=page.locator('#stage').bounding_box()
        assert page.locator('#layout').bounding_box()['y']==0
        assert stage['y']+stage['height']<=page.evaluate('innerHeight'),stage
        page.get_by_role('button',name='Settings',exact=True).click()
        expect(page.locator('#settings-form')).to_be_visible()
        page.get_by_role('button',name='Close dialog',exact=True).click()
        page.screenshot(path=str(out/'ownership-fullscreen.png'))
        page.get_by_role('button',name='Exit fullscreen',exact=True).click()
        expect(page.locator('.topbar')).to_be_visible()
        menu();load('incomingCounter')
        page.get_by_role('button',name='Decline trade',exact=True).click()
        expect(page.locator('#dialog-title')).to_have_text('Make a counteroffer?')
        page.get_by_role('button',name='Build counteroffer',exact=True).click()
        expect(page.locator('#dialog-title')).to_have_text('Build a counteroffer')
        expect(page.locator('.counter-partner')).to_contain_text('Ben')
        expect(page.locator('#trade-partner')).to_have_count(0)
        expect(page.locator('input[name=giveCash]')).to_have_value('100')
        expect(page.locator('input[name=receive][value="1"]')).to_be_checked()
        page.locator('input[name=giveCash]').fill('90')
        page.get_by_role('button',name='Review trade',exact=True).click()
        expect(page.locator('#dialog-title')).to_have_text('Review your counteroffer')
        expect(page.locator('#dialog .trade-summary')).to_contain_text('$1,410')
        page.screenshot(path=str(out/'counteroffer-review.png'))
        page.get_by_role('button',name='Send counteroffer',exact=True).click()
        expect(page.locator('.portfolio')).to_contain_text('Copper Lane',timeout=10000)
        expect(page.locator('#player-ledger')).to_contain_text('$1,410')
        menu();load('incomingCounter')
        page.get_by_role('button',name='Decline trade',exact=True).click()
        page.get_by_role('button',name='Decline without counteroffer',exact=True).click()
        expect(page.locator('#dialog')).not_to_be_visible()
        expect(page.locator('#event-popup')).to_be_hidden()
        menu();load('lowOffer')
        expect(page.locator('#event-popup')).to_contain_text('Counteroffer from Ben',timeout=10000)
        page.get_by_role('button',name='Accept trade',exact=True).click()
        expect(page.locator('.portfolio')).to_contain_text('Copper Lane')
        expect(page.locator('#player-ledger')).to_contain_text('$1,411')
        for width,height in [(390,844),(844,390)]:
            page.set_viewport_size({'width':width,'height':height})
            assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        assert not errors,errors
        print(json.dumps({'result':'PASS','flows':['compact receipt and auto-dismiss','ownership labels and deed popup','native fullscreen and settings','human counteroffer accepted by bot','decline without counteroffer','bot counteroffer accepted by human','mobile bounds'],'page_errors':errors}))
    finally:browser.close()
