import os,json
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
BASE=os.environ.get('EMPIRE_URL','http://127.0.0.1:5173')
OUT=Path('test-artifacts');OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(channel='chrome',headless=True,args=['--enable-webgl','--use-angle=swiftshader'])
 context=browser.new_context(viewport={'width':1440,'height':960})
 page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(BASE);page.wait_for_load_state('networkidle')
 expect(page.get_by_role('button',name='Play Solo',exact=True)).to_be_visible(timeout=5000)
 page.screenshot(path=str(OUT/'menu-desktop.png'),full_page=True)
 page.get_by_role('button',name='Play Solo',exact=True).click()
 page.get_by_label('Your name').fill('Ada')
 page.get_by_role('button',name='Start game',exact=True).click()
 expect(page.get_by_role('button',name='Roll dice',exact=True)).to_be_enabled(timeout=30000)
 page.get_by_role('button',name='Roll dice',exact=True).click()
 expect(page.locator('#game-info')).to_contain_text('Turn')
 page.get_by_role('button',name='Save game',exact=True).click()
 expect(page.locator('#toast')).to_contain_text('saved')
 page.screenshot(path=str(OUT/'game-desktop.png'),full_page=True)
 page.reload();page.wait_for_load_state('networkidle')
 page.get_by_role('button',name='Continue Saved Game',exact=True).click()
 expect(page.locator('#game-info')).to_contain_text('Ada')
 page.get_by_role('button',name='Properties',exact=True).click()
 expect(page.get_by_role('dialog')).to_be_visible()
 page.get_by_role('button',name='Copper Lane',exact=False).click()
 expect(page.locator('#inspector')).to_contain_text('Copper Lane')
 page.set_viewport_size({'width':390,'height':844})
 page.screenshot(path=str(OUT/'game-mobile.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile horizontal overflow'
 assert page.locator('canvas').count()>0,'No 3D canvas'
 page.set_viewport_size({'width':1440,'height':960})
 page.get_by_role('button',name='Main menu',exact=True).click()
 page.get_by_role('button',name='Create LAN Game',exact=True).click()
 page.get_by_label('Your name').fill('Host Ada')
 page.get_by_label('Bot opponents').select_option('0')
 page.get_by_role('button',name='Create room',exact=True).click()
 expect(page.locator('#room-code')).to_be_visible(timeout=10000)
 code=page.locator('#room-code').inner_text().strip()
 othercontext=browser.new_context(viewport={'width':390,'height':844});other=othercontext.new_page();other.on('pageerror',lambda e:errors.append(str(e)))
 other.goto(BASE+'/?room='+code);other.wait_for_load_state('networkidle')
 other.get_by_label('Your name').fill('Guest Ben')
 other.get_by_role('button',name='Join room',exact=True).click()
 other.get_by_role('button',name='Ready to play',exact=True).click()
 page.get_by_role('button',name='Start match',exact=True).click()
 expect(page.locator('#game-info')).to_contain_text('Turn',timeout=10000)
 expect(other.locator('#game-info')).to_contain_text('Turn',timeout=10000)
 page.screenshot(path=str(OUT/'lan-desktop.png'),full_page=True)
 other.screenshot(path=str(OUT/'lan-mobile.png'),full_page=True)
 actor=page if page.get_by_role('button',name='Roll dice',exact=True).is_enabled() else other
 actor.get_by_role('button',name='Roll dice',exact=True).click()
 expect(page.locator('#revision')).to_have_text('1',timeout=10000)
 expect(other.locator('#revision')).to_have_text('1',timeout=10000)
 assert page.locator('#player-ledger').inner_text()==other.locator('#player-ledger').inner_text(),'LAN ledger mismatch'
 other.reload();other.wait_for_load_state('networkidle');other.get_by_role('button',name='Rejoin LAN Game',exact=True).click()
 expect(other.locator('#revision')).to_have_text('1',timeout=10000)
 assert not errors,'Browser exceptions: '+str(errors)
 print(json.dumps({'result':'PASS','flows':['solo roll','manual save','resume','property selection','mobile layout','two-browser LAN','state synchronization','LAN reconnect'],'page_errors':errors,'screenshots':str(OUT)},indent=2))
 browser.close()
